import {chromium} from 'playwright';
import fs from 'node:fs/promises';
const root=process.cwd();
const dir=root+'/docs/design/kusanagi_20261021';
await fs.mkdir(dir,{recursive:true});
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1280,height:720},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto('http://127.0.0.1:4400/tools/browser/weapon_thumbs.html?ids=uchigatana,kusanagi');
await page.waitForFunction(()=>window.thumbs?.done);
for(const {id,url} of await page.evaluate(()=>window.thumbs.list))if(id==='kusanagi')await fs.writeFile(root+'/public/ui/weapons/'+id+'.webp',Buffer.from(url.split(',')[1],'base64'));
await page.screenshot({path:dir+'/models.png'});
await page.goto('http://127.0.0.1:4400/?test=1&cards=uchigatana,kusanagi&foe=bran&foeWeapon=tree_branch&stage=clearing&foeWhiff=1');
await page.waitForFunction(()=>window.game?.state==='menu',{},{timeout:120000});
console.log('menu loaded');await page.locator('#btnStart').click();
await page.waitForFunction(()=>game.draw.stage==='choose'&&game.draw.t>=.5);
await page.locator('.wcard').nth(1).click();
await page.evaluate(()=>new Promise((resolve,reject)=>{const timeout=setTimeout(()=>reject(new Error('reveal timeout')),20000);function tick(){if(game.draw.others&&game.draw.foe){game.draw.hold=true;clearTimeout(timeout);resolve();}else requestAnimationFrame(tick);}tick();}));
await page.evaluate(()=>document.fonts.ready);
await page.screenshot({path:dir+'/cards-desktop.png'});
console.log('cards captured');const cards=await page.locator('.wcard').allTextContents();
await page.setViewportSize({width:844,height:390});
await page.waitForTimeout(400);
await page.screenshot({path:dir+'/cards-mobile.png'});
await page.evaluate(()=>game.draw.hold=false);
await page.waitForFunction(()=>game.state==='fight');
await page.waitForTimeout(2500);
await page.screenshot({path:dir+'/equipped.png'});
const state=await page.evaluate(()=>({weapon:game.player.weapon.id,tier:game.player.weapon.tier,power:game.player.weapon.power,tradition:game.player.swordArt.tradition,grip:game.player.weapon.grip,enemy:game.enemy.weapon.id,stage:game.stage.id,state:game.state,position:game.player.sword.translation()}));
await fs.writeFile(dir+'/browser.json',JSON.stringify({cards,state,errors},null,2)+'\n');
console.log(JSON.stringify({cards,state,errors}));
await browser.close();
if(errors.length)process.exitCode=1;
