import {chromium} from 'playwright';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const b=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await b.newPage({viewport:{width:844,height:390},hasTouch:true,isMobile:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4401/?test=1&weapon=kusanagi&foe=bran&foeWeapon=tree_branch&stage=clearing&foeWhiff=1');
await page.waitForFunction(()=>window.game?.state==='menu',null,{timeout:120000});
await page.locator('#btnStart').tap();
await page.waitForFunction(()=>game.state==='fight');
await page.waitForTimeout(6000);
const cdp=await page.context().newCDPSession(page);
const box=await page.locator('#btnParry').boundingBox();
assert(box);
await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:box.x+box.width/2,y:box.y+box.height/2}]});
await page.waitForTimeout(200);
const held=await page.evaluate(()=>game.playerGuard.held);
await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
await page.waitForTimeout(300);
const released=await page.evaluate(()=>!game.playerGuard.held);
console.log({held,released});assert(held&&released);
const state=await page.evaluate(()=>({weapon:game.player.weapon.id,school:game.player.swordArt.tradition,state:game.state,finite:Object.values(game.player.sword.translation()).every(Number.isFinite),savedJourney:localStorage.getItem('stillness.fork.journey.v1')}));
assert.equal(state.weapon,'kusanagi');assert.equal(state.school,'japanese');assert(state.finite);assert.equal(state.savedJourney,null);assert.equal(errors.length,0);
const out=process.cwd()+'/docs/design/kusanagi_20261021';
await page.screenshot({path:out+'/touch-built.png'});
await fs.writeFile(out+'/touch.json',JSON.stringify({builtPreview:true,held,released,state,errors},null,2)+'\n');
console.log({held,released,state,errors});await b.close();
