/** 한 판 싸움꾼 자리 수 (자리 0 ~ 3 — 충돌 비트 16 개를 다 쓴다, fighter.js) */
export const MAX_FIGHTERS = 4;

/** 자리 번호 → 기본 편 (0 · 2 → 0 편, 1 · 3 → 1 편) */
export const teamOfIndex = (index) => index % 2;

/**
 * 같은 편인가 (자기 자신 포함). 편이 적히지 않은 가짜 싸움꾼(시험 도구)은 같은 몸일 때만 같은 편 —
 *  예전 판정 `a === b` 와 같다. 1:1 에서는 편 = 자리 번호라 이 판정이 `a === b` 와 늘 같은 답이다
 */
export function sameSide(a, b) {
  if (!a || !b) return false;
  return a === b || (a.team != null && a.team === b.team);
}
